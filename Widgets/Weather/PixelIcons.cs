    // ═══════════════════════════════════════════
    //  Public API
    // ═══════════════════════════════════════════
    public static void Draw(Canvas canvas, string iconType, int pixelSize = 3, Color? color = null)
    {
        canvas.Children.Clear();

        var brush = new SolidColorBrush(color ?? Colors.White);
        var pattern = GetPattern(iconType);

        double spacing = pixelSize * 1.15;

        for (int row = 0; row < pattern.Length; row++)
        {
            for (int col = 0; col < pattern[row].Length; col++)
            {
                if (pattern[row][col] == 1)
                {
                    var dot = new Ellipse
                    {
                        Width = pixelSize,
                        Height = pixelSize,
                        Fill = brush
                    };
                    Canvas.SetLeft(dot, col * spacing);
                    Canvas.SetTop(dot, row * spacing);
                    canvas.Children.Add(dot);
                }
            }
        }
    }

    // ═══════════════════════════════════════════
    //  Patterns (از تصویر)
    // ═══════════════════════════════════════════
    private static int[][] GetPattern(string iconType)
    {
        return iconType switch
        {
            "sun" => SunPattern(),
            "cloud" => CloudPattern(),
            "partly" => PartlyCloudyPattern(),
            "rain" => RainPattern(),
            "heavy_rain" => HeavyRainPattern(),
            "thunder" => ThunderPattern(),
            "snow" => SnowPattern(),
            "fog" => FogPattern(),
            "wind" => WindPattern(),
            "moon" => MoonPattern(),
            _ => CloudPattern()
        };
    }

